#ifndef SHADOWFOX_MASK_H
#define SHADOWFOX_MASK_H

#include <stddef.h>

/* Маскировка ссылок для страницы.

   Ключ — учётные данные, и отдавать его браузеру на каждом обновлении
   незачем: достаточно показать, куда ведёт ссылка. Прятать в разметке
   было бы обманом — текст всё равно уехал бы в браузер и осел в кеше.

   Отдельным файлом, потому что здесь уже было переполнение стека, а
   проверить его в составе веб-обработчика нельзя. */

#define MASK_MARK "\xe2\x80\xa2\xe2\x80\xa2\xe2\x80\xa2\xe2\x80\xa2"   /* •••• */

/* Одна строка: ссылка на узел с закрытым uuid и sid, ссылка на подписку с
   закрытым путём, всё прочее — целиком маска. Строка без схемы — это
   подписка в base64, то есть весь ключ; показывать её нельзя. */
void mask_link(const char *in, char *out, size_t size);

/* Многострочный текст, построчно. Пустые строки остаются пустыми. */
void mask_nodes(const char *in, char *out, size_t size);

#endif /* SHADOWFOX_MASK_H */
