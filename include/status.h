#ifndef SHADOWFOX_STATUS_H
#define SHADOWFOX_STATUS_H

#include "config.h"

/* Состояние демона одной командой.

   Часть сведений знает только сам демон — счётчики перехвата, время
   запуска, — поэтому он выкладывает их в файл. Всё остальное читается
   из системы на месте: сколько адресов в наборах, стоят ли правила,
   какие процессы живы. Так вывод показывает, что есть на самом деле,
   а не то, что демон о себе думает. */

struct engine;

/* Путь к файлу состояния: рядом с pid-файлом, с тем же именем.
   Так он следует за настройками, а не живёт по зашитому пути. */
void status_path(const config_t *cfg, char *dst, unsigned dst_size);

/* Демон выкладывает свои счётчики. Вызывается периодически. */
void status_write(const struct engine *e, const config_t *cfg);

/* Печатает полную картину. Возвращает 0, если демон работает. */
int  status_print(const config_t *cfg);

#endif /* SHADOWFOX_STATUS_H */
